#!/usr/bin/env node
/**
 * Emit frontend-UI/src/components/brand/Logo.tsx from the built SVGs.
 *
 * The React components inline the mark and wordmark geometry so the app
 * never loads a raster logo: the mark is filled with the app's primary token
 * and the wordmark text with currentColor, so both follow the theme with no
 * duplicate light/dark images and no flash on hydration.
 *
 * Re-run after build-all.cjs whenever mark-spec.cjs or the typography
 * changes. Never hand-edit Logo.tsx.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..', '..', '..');
const brand = path.join(root, 'frontend-UI', 'public', 'brand');
const out = path.join(root, 'frontend-UI', 'src', 'components', 'brand', 'Logo.tsx');

const read = (f) => fs.readFileSync(path.join(brand, f), 'utf8');
const viewBox = (svg) => svg.match(/viewBox="([^"]+)"/)[1];
const rects = (svg) =>
  [...svg.matchAll(/<rect x="([^"]+)" y="([^"]+)" width="([^"]+)" height="([^"]+)" rx="([^"]+)"/g)].map(
    ([, x, y, width, height, rx]) => ({ x, y, width, height, rx })
  );
const textPath = (svg) => {
  const m = svg.match(/<path fill="#0F1729" d="([^"]+)"/);
  if (!m) throw new Error('wordmark.svg: ink text path not found');
  return m[1];
};

const mark = read('mark.svg');
const wordmark = read('wordmark.svg');
const markRects = rects(mark);
const wmRects = rects(wordmark);
if (markRects.length !== 3 || wmRects.length !== 3) throw new Error('expected three bars');
if (/<text|font-face|href|url\(/.test(wordmark)) throw new Error('wordmark.svg is not outline-only');

const rectJsx = (r, indent) =>
  `${indent}<rect x="${r.x}" y="${r.y}" width="${r.width}" height="${r.height}" rx="${r.rx}" />`;

const tsx = `// GENERATED by docs/brand/tools/build-components.cjs from
// public/brand/mark.svg and public/brand/wordmark.svg. Do not edit by hand;
// change docs/brand/tools/mark-spec.cjs and rebuild.
//
// The mark is filled with the primary token and the wordmark text with
// currentColor, so both follow the active theme without separate light and
// dark images.

import type { SVGProps } from "react";

type LogoProps = Omit<SVGProps<SVGSVGElement>, "viewBox" | "children"> & {
  /** Accessible name. Pass an empty string when the logo is purely decorative next to visible text. */
  title?: string;
};

const MARK_FILL = "hsl(var(--primary))";

/** The Track Toolkit icon mark: three stacked tracks, the middle one moved. */
export function BrandMark({ title = "Track Toolkit", ...props }: LogoProps) {
  const decorative = title === "";
  return (
    <svg
      viewBox="${viewBox(mark)}"
      role={decorative ? undefined : "img"}
      aria-hidden={decorative ? true : undefined}
      aria-label={decorative ? undefined : title}
      fill={MARK_FILL}
      {...props}
    >
${markRects.map((r) => rectJsx(r, '      ')).join('\n')}
    </svg>
  );
}

/** The horizontal Track Toolkit wordmark. Text inherits the CSS color. */
export function BrandWordmark({ title = "Track Toolkit", ...props }: LogoProps) {
  const decorative = title === "";
  return (
    <svg
      viewBox="${viewBox(wordmark)}"
      role={decorative ? undefined : "img"}
      aria-hidden={decorative ? true : undefined}
      aria-label={decorative ? undefined : title}
      {...props}
    >
      <g fill={MARK_FILL}>
${wmRects.map((r) => rectJsx(r, '        ')).join('\n')}
      </g>
      <path
        fill="currentColor"
        d="${textPath(wordmark)}"
      />
    </svg>
  );
}
`;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, tsx);
console.log('wrote', path.relative(root, out), tsx.length, 'bytes');
